    <script>
    (function() {
        const wrapper = document.querySelector('.ba-slider-wrapper');
        if (!wrapper) return;

        const cards = wrapper.querySelectorAll('.ba-card');
        const dots = document.querySelectorAll('.ba-dot');
        const prevBtn = document.querySelector('.ba-prev');
        const nextBtn = document.querySelector('.ba-next');
        let currentIndex = 0;
        const total = cards.length;

        function showCard(idx) {
            cards.forEach(c => c.classList.remove('active'));
            dots.forEach(d => d.classList.remove('active'));
            cards[idx].classList.add('active');
            if (dots[idx]) dots[idx].classList.add('active');
            currentIndex = idx;
            // Reset handle for this card
            initCardHandle(cards[idx]);
        }

        function initCardHandle(card) {
            const compare = card.querySelector('.ba-compare');
            const beforeWrap = card.querySelector('.ba-before-wrap');
            const handle = card.querySelector('.ba-handle');
            if (!compare || !beforeWrap || !handle) return;

            let dragging = false;

            function setPosition(clientX) {
                const rect = compare.getBoundingClientRect();
                // For RTL: right edge = 0%, left edge = 100%
                const x = clientX - rect.right; // negative values in RTL
                const pct = Math.max(0, Math.min(100, (-x / rect.width) * 100));
                beforeWrap.style.width = pct + '%';
                handle.style.right = pct + '%';
                // Keep after overlay aligned with handle
                const afterOverlay = card.querySelector('.ba-overlay-after');
                if (afterOverlay) afterOverlay.style.right = pct + '%';
            }

            // Start at 50%
            setPosition(compare.getBoundingClientRect().right - compare.getBoundingClientRect().width / 2);

            // Mouse events
            compare.addEventListener('mousedown', (e) => {
                e.preventDefault();
                dragging = true;
                compare.style.cursor = 'ew-resize';
            });

            window.addEventListener('mousemove', (e) => {
                if (!dragging) return;
                setPosition(e.clientX);
            });

            window.addEventListener('mouseup', () => {
                dragging = false;
                if (compare) compare.style.cursor = 'ew-resize';
            });

            // Touch events (mobile)
            compare.addEventListener('touchstart', (e) => {
                dragging = true;
            }, { passive: true });

            window.addEventListener('touchmove', (e) => {
                if (!dragging) return;
                setPosition(e.touches[0].clientX);
            }, { passive: true });

            window.addEventListener('touchend', () => {
                dragging = false;
            });
        }

        // Init first card
        if (cards.length > 0) {
            showCard(0);
        }

        // Dot click
        dots.forEach(dot => {
            dot.addEventListener('click', () => {
                const idx = parseInt(dot.dataset.go) - 1;
                showCard(idx);
            });
        });

        // Previous / Next
        if (prevBtn) {
            prevBtn.addEventListener('click', () => {
                const idx = (currentIndex - 1 + total) % total;
                showCard(idx);
            });
        }
        if (nextBtn) {
            nextBtn.addEventListener('click', () => {
                const idx = (currentIndex + 1) % total;
                showCard(idx);
            });
        }
    })();
    </script>

