    const increaseFontSize = document.getElementById('increaseFontSize');
    const decreaseFontSize = document.getElementById('decreaseFontSize');
    
    increaseFontSize.addEventListener('click', () => {
        document.body.classList.remove('large-text', 'larger-text');
        fontSizeLevel = Math.min(fontSizeLevel + 1, 2);
        if (fontSizeLevel === 1) document.body.classList.add('large-text');
        if (fontSizeLevel === 2) document.body.classList.add('larger-text');
        saveSettings();
    });
    
    decreaseFontSize.addEventListener('click', () => {
        document.body.classList.remove('large-text', 'larger-text');
        fontSizeLevel = Math.max(fontSizeLevel - 1, 0);
        if (fontSizeLevel === 1) document.body.classList.add('large-text');
        saveSettings();
    });
    
    // High Contrast
    document.getElementById('highContrast').addEventListener('change', function() {
        document.body.classList.toggle('high-contrast', this.checked);
